CREATE TABLE IF NOT EXISTS public.uploads (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 filename text NOT NULL, original_name text NOT NULL, file_size bigint NOT NULL,
 upload_date timestamptz NOT NULL DEFAULT now(),
 status text NOT NULL DEFAULT 'processing' CHECK(status IN ('processing','completed','error')),
 total_files integer NOT NULL DEFAULT 0, error_message text
);
CREATE TABLE IF NOT EXISTS public.extracted_files (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 upload_id integer NOT NULL REFERENCES public.uploads(id) ON DELETE CASCADE,
 filename text NOT NULL, file_path text NOT NULL,
 file_type text NOT NULL CHECK(file_type IN ('text','audio','image','other')),
 file_size bigint NOT NULL, mime_type text, extracted_date timestamptz NOT NULL DEFAULT now(),
 content_text text, transcription text, transcription_status text NOT NULL DEFAULT 'not_applicable',
 metadata text
);
CREATE TABLE IF NOT EXISTS public.file_contents (
 path text PRIMARY KEY,
 upload_id integer NOT NULL REFERENCES public.uploads(id) ON DELETE CASCADE,
 contents bytea NOT NULL
);
CREATE INDEX IF NOT EXISTS extracted_files_upload_idx ON public.extracted_files(upload_id);
CREATE INDEX IF NOT EXISTS extracted_files_date_idx ON public.extracted_files(extracted_date);
ALTER TABLE public.uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.extracted_files ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.file_contents ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.uploads, public.extracted_files, public.file_contents FROM anon, authenticated;
